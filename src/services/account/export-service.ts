import 'server-only';
import { prisma } from '@/lib/prisma';

export async function buildAccountExport(userId: string) {
  const [
    profile,
    preferences,
    consents,
    planDrafts,
    planVersions,
    meals,
    savedMeals,
    dayStates,
    weights,
    reflections,
    mediaAssets,
    jobs,
    aiAnalyses,
    userFoods,
  ] = await Promise.all([
    prisma.profile.findUnique({ where: { userId } }),
    prisma.preferences.findUnique({ where: { userId } }),
    prisma.consent.findMany({ where: { userId } }),
    prisma.planDraft.findMany({ where: { userId } }),
    prisma.dietPlanVersion.findMany({ where: { userId } }),
    prisma.meal.findMany({ where: { userId }, include: { items: true } }),
    prisma.savedMeal.findMany({ where: { userId } }),
    prisma.dayState.findMany({ where: { userId } }),
    prisma.weightEntry.findMany({ where: { userId } }),
    prisma.reflection.findMany({ where: { userId } }),
    prisma.mediaAsset.findMany({
      where: { userId },
      select: {
        id: true,
        purpose: true,
        state: true,
        mimeType: true,
        byteSize: true,
        retentionDeadline: true,
        deletedAt: true,
        createdAt: true,
      },
    }),
    prisma.job.findMany({
      where: { userId },
      select: {
        id: true,
        type: true,
        state: true,
        safeErrorCode: true,
        createdAt: true,
        updatedAt: true,
      },
    }),
    prisma.aiAnalysis.findMany({
      where: { userId },
      select: {
        id: true,
        purpose: true,
        provider: true,
        model: true,
        draftType: true,
        draftId: true,
        draftRevision: true,
        schemaVersion: true,
        promptVersion: true,
        state: true,
        safeErrorCode: true,
        createdAt: true,
        completedAt: true,
      },
    }),
    prisma.userFood.findMany({ where: { userId } }),
  ]);
  return {
    manifest: { format: 'dietyaar-export', version: 1, generatedAt: new Date().toISOString() },
    profile,
    preferences,
    consents,
    planDrafts,
    planVersions,
    meals,
    savedMeals,
    dayStates,
    weightEntries: weights,
    reflections,
    mediaAssets,
    jobs,
    aiAnalyses,
    userFoods,
  };
}
